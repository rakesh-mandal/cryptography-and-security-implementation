#include <stdio.h>
#include <stdlib.h>
#include <x86intrin.h>

#include "chacha20.h"

int main(void)
{
    /* Test Vector Key (256-bit / 32 bytes) */
    u8 key[CHACHA20_KEY_SIZE] = {
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f
    };

    /* Test Vector Nonce (96-bit / 12 bytes) */
    u8 nonce[CHACHA20_NONCE_SIZE] = {
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x4a,
        0x00, 0x00, 0x00, 0x00
    };

    /* Initial block counter */
    u32 counter = 1;

    /* Plaintext byte array */
    u8 plain_text[] = {
        0x4c, 0x61, 0x64, 0x69, 0x65, 0x73, 0x20, 0x61,
        0x6e, 0x64, 0x20, 0x47, 0x65, 0x6e, 0x74, 0x6c,
        0x65, 0x6d, 0x65, 0x6e, 0x20, 0x6f, 0x66, 0x20,
        0x74, 0x68, 0x65, 0x20, 0x63, 0x6c, 0x61, 0x73,
        0x73, 0x20, 0x6f, 0x66, 0x20, 0x27, 0x39, 0x39,
        0x3a, 0x20, 0x49, 0x66, 0x20, 0x49, 0x20, 0x63,
        0x6f, 0x75, 0x6c, 0x64, 0x20, 0x6f, 0x66, 0x66,
        0x65, 0x72, 0x20, 0x79, 0x6f, 0x75, 0x20, 0x6f,
        0x6e, 0x6c, 0x79, 0x20, 0x6f, 0x6e, 0x65, 0x20,
        0x74, 0x69, 0x70, 0x20, 0x66, 0x6f, 0x72, 0x20,
        0x74, 0x68, 0x65, 0x20, 0x66, 0x75, 0x74, 0x75,
        0x72, 0x65, 0x2c, 0x20, 0x73, 0x75, 0x6e, 0x73,
        0x63, 0x72, 0x65, 0x65, 0x6e, 0x20, 0x77, 0x6f,
        0x75, 0x6c, 0x64, 0x20, 0x62, 0x65, 0x20, 0x69,
        0x74, 0x2e
    };

    
    size_t length = sizeof(plain_text);

    u8 *ciphertext = malloc(length);
    u8 *decrypted  = malloc(length + 1); // +1 byte for null terminator

    if (!ciphertext || !decrypted) {
        printf("Memory allocation failed.\n");
        free(ciphertext);
        free(decrypted);
        return 1;
    }

    /* Encrypt & measure CPU cycles */
    const int ITER = 100000;
    
    unsigned long long start = __rdtsc();
    for (int i = 0; i < ITER; i++) {
    chacha20_encrypt(ciphertext, plain_text, length,
                     key, counter, nonce);
    }
    unsigned long long end = __rdtsc();

    unsigned long long cycles = end - start;
    double cpb = (double)cycles / (ITER * length);


    /* Decrypt back to verify correctness */
    chacha20_encrypt(
        decrypted,
        ciphertext,
        length,
        key,
        counter,
        nonce
    );

    /* Safely append null-terminator for printing decrypted string */
    decrypted[length] = '\0';

    /* Display Results */
    printf("========== ChaCha20 Demo ==========\n\n");
    printf("Message Length: %zu bytes\n\n", length);

    /* Print Ciphertext in Hex */
    printf("Ciphertext (Hex):\n");
    for (size_t i = 0; i < length; i++) {
        printf("%02X ", ciphertext[i]);
        if ((i + 1) % 16 == 0) printf("\n");
    }
    printf("\n\n");

    

    printf("CPU Cycles  = %llu\n", cycles);
    printf("Cycles/Byte = %.2f\n\n", cpb);

    /* Print Decrypted Text */
    printf("Decrypted Plaintext:\n%s\n", decrypted);

    /* Clean up memory */
    free(ciphertext);
    free(decrypted);

    return 0;
}
